@dataclass
class EnvState:
    """环境状态数据类 - 描述当前任务的上下文，供 LLM 感知工作流阶段和任务参数。"""

    writing_mode: str = ""          # 当前写作模式（如"战略叙事"）
    mode_value: str = ""            # 模式枚举值（如"strategic_narrative"）
    subtype: str = ""               # 文种子类型（如"feature"）
    stage: str = ""                 # 当前工作流阶段（如"审查阶段"）
    doc_type: str = ""              # 文种（如"通讯"）
    media_style: str = ""           # 媒体风格（如"人民日报"）
    style_intensity: float = 1.0    # 风格强度（0.0-1.0）
    purpose: str = ""               # 核心写作目的
    primary_audience: str = ""      # 第一读者
    length_hint: Optional[int] = None  # 期望篇幅
    extra: Dict[str, str] = field(default_factory=dict)  # 额外上下文
    # 工作流迭代维度（1.4）：多轮审查时让 LLM 感知轮次与历史问题
    iteration_count: int = 0      # 总审查轮数
    draft_version: int = 0        # 当前稿件版本号（第几轮）
    previous_issues: str = ""     # 上一轮发现的问题摘要

    def render(self, exclude_fields: Optional[List[str]] = None) -> str:
        """渲染为环境状态文本

        exclude_fields: 需要排除的字段名列表（下游 prompt 已有详述的字段避免重复注入）
        """
        excluded = set(exclude_fields or [])
        lines = []
        if self.writing_mode and "writing_mode" not in excluded:
            lines.append(f"- 当前写作模式：{self.writing_mode}（{self.mode_value}）")
        if self.subtype and "subtype" not in excluded:
            lines.append(f"- 文种子类型：{self.subtype}")
        if self.stage and "stage" not in excluded:
            lines.append(f"- 当前工作流阶段：{self.stage}")
        if self.doc_type and "doc_type" not in excluded:
            lines.append(f"- 文种：{self.doc_type}")
        if self.media_style and "media_style" not in excluded:
            intensity_label = self._intensity_label(self.style_intensity)
            lines.append(f"- 媒体风格：{self.media_style}（{intensity_label}）")
        if self.purpose and "purpose" not in excluded:
            lines.append(f"- 核心写作目的：{self.purpose}")
        if self.primary_audience and "primary_audience" not in excluded:
            lines.append(f"- 第一读者：{self.primary_audience}")
        if self.length_hint and "length_hint" not in excluded:
            lines.append(f"- 期望篇幅：约{self.length_hint}字")
        if "iteration" not in excluded and self.iteration_count:
            lines.append(f"- 审查轮次：第{self.draft_version}/{self.iteration_count}轮")
        if "iteration" not in excluded and self.previous_issues:
            lines.append(f"- 上一轮已发现问题：{self.previous_issues[:120]}")
        for key, value in self.extra.items():
            if key not in excluded:
                lines.append(f"- {key}：{value}")
        return "\n".join(lines) if lines else "（暂无激活的任务上下文，等待用户发起写作请求）"

    @staticmethod
    def _intensity_label(intensity: float) -> str:
        if intensity >= 0.9:
            return "完整强度"
        elif intensity >= 0.7:
            return "标准强度"
        elif intensity >= 0.5:
            return "适度风格"
        elif intensity >= 0.3:
            return "轻度风格"
        else:
            return "极简风格"


